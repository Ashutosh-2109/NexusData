import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1365,height:950}});
await page.goto('http://127.0.0.1:3011/');
await page.waitForFunction(()=>{const s=document.querySelector('[role=status]')?.textContent?.trim().toLowerCase();return s&&s!=='loading';},{timeout:40000});
const status=await page.getByRole('status').first().innerText();
assert.equal(status,'STALE');
const states=page.locator('.leaflet-interactive[fill="#0f172a"]');
assert.ok(await states.count()>0,'state polygons must render');
await page.getByLabel('State averages').check();
assert.equal(await page.getByLabel('State averages').isChecked(),true);
assert.ok(await page.locator('.leaflet-interactive[fill-opacity="0.42"]').count()>0,'state choropleth must recolor states');
const markers=page.locator('.leaflet-interactive[fill-opacity="0.9"]');
await page.waitForFunction(()=>document.querySelectorAll('.leaflet-interactive[fill-opacity="0.9"]').length>=20,{timeout:30000});
await markers.first().dispatchEvent('click');
await page.waitForSelector('text=Indicative scenario',{timeout:40000});
const panel=await page.locator('aside').last().innerText();
assert.match(panel,/48-hour/);assert.match(panel,/Development areas/);assert.match(panel,/Indicative analysis, not policy guidance/);
console.log(JSON.stringify({status,states:await states.count(),choropleth:'recolored',markers:await markers.count(),cityDetail:/Mumbai/.test(panel),historyChart:panel.includes('48-hour'),development:panel.includes('Development areas'),scenarioDisclaimer:panel.includes('Indicative analysis, not policy guidance')}));
await browser.close();
