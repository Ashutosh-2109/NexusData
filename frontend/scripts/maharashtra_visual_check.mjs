import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const out='../docs/screenshots';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const pageErrors=[]; page.on('pageerror',error=>pageErrors.push(error.message));
await page.goto('http://127.0.0.1:3011/maharashtra',{waitUntil:'networkidle'});
await page.waitForSelector('svg[aria-label="Map of Maharashtra districts"] path[data-district]');
await page.waitForTimeout(600);
assert.equal(await page.locator('path.mah-district-shape').count(),36,'all 36 district polygons must render');
assert.ok(await page.locator('.mah-inset path').count()>=4,'Mumbai-area inset districts must render');
const populationColors=await page.locator('path.mah-district-shape').evaluateAll(paths=>paths.map(path=>path.getAttribute('fill')));
await page.screenshot({path:`${out}/maharashtra-map-at-rest.png`,fullPage:true});
const path=page.locator('path[data-district="Pune"]').first();
const point=await path.evaluate(el=>{const b=el.getBoundingClientRect();for(let y=b.top+2;y<b.bottom-2;y+=3)for(let x=b.left+2;x<b.right-2;x+=3)if(document.elementFromPoint(x,y)===el)return{x,y};return null;});
if(!point) throw new Error('No exposed interior hit point found for Pune district');
await page.mouse.move(point.x,point.y);
await page.waitForSelector('.mah-hover-card');
await page.waitForTimeout(200);
await page.screenshot({path:`${out}/maharashtra-map-hover-pune.png`,fullPage:true});
await path.dispatchEvent('click');
await page.waitForSelector('.mah-selected-panel .mah-district-card-pinned');
assert.ok((await page.locator('.mah-selected-panel').innerText()).toLowerCase().includes('land and nutrition'),'pinned card must contain the full district detail groups');
await page.screenshot({path:`${out}/maharashtra-map-pinned-pune.png`,fullPage:true});
await page.getByRole('button',{name:'Close district details'}).click();
await page.screenshot({path:`${out}/maharashtra-mumbai-inset.png`,fullPage:false});
await page.getByLabel('Maharashtra map metric').selectOption('health_facilities_per_lakh');
await page.waitForTimeout(300);
assert.notDeepEqual(await page.locator('path.mah-district-shape').evaluateAll(paths=>paths.map(path=>path.getAttribute('fill'))),populationColors,'metric switch must recolor districts');
assert.ok(await page.locator('path.mah-district-shape[fill="url(#no-data-hatch)"]').count()>0,'null metrics must use hatch fill');
await page.getByRole('tab',{name:'Airport connectivity'}).click();
await page.waitForTimeout(250);
assert.ok(await page.locator('.mah-layer-list article').count()>0,'airport layer must show workbook traffic records');
await page.getByLabel('Add district').selectOption('pune');
assert.ok(await page.getByText('Cross-district profile').count());
await page.screenshot({path:`${out}/maharashtra-no-data-hatching.png`,fullPage:true});
await page.getByRole('button',{name:/Present the story/}).click();
await page.waitForSelector('.mah-deck');
await page.screenshot({path:`${out}/maharashtra-present-slide-1.png`,fullPage:false});
for(let i=0;i<7;i++) await page.getByRole('button',{name:'Next →'}).click();
await page.waitForTimeout(200);
await page.screenshot({path:`${out}/maharashtra-present-slide-8.png`,fullPage:false});
await page.getByRole('button',{name:/Close presentation/}).click();
await page.screenshot({path:`${out}/maharashtra-dark-theme.png`,fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo(0,0));
await page.waitForTimeout(700);
const mobile=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,body:document.body.scrollWidth}));
await page.screenshot({path:`${out}/maharashtra-mobile-390.png`,fullPage:true});
assert.equal(mobile.document,390,'390px view must not scroll horizontally');
assert.deepEqual(pageErrors,[],'browser should have no uncaught errors');
console.log(JSON.stringify({screenshots:fs.readdirSync(out).filter(x=>x.endsWith('.png')),mobile,mainDistricts:36,insetDistricts:await page.locator('.mah-inset path').count(),hatchCount:'verified',metricRecolor:'verified'},null,2));
await browser.close();



